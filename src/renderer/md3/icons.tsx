export function Icon({
  name,
  size = 20,
  className,
  style,
}: {
  name: IconName;
  size?: number;
  className?: string;
  style?: React.CSSProperties;
}): React.ReactElement {
  // Unknown names must not crash the renderer; fall back to a neutral dot so a
  // typo is visible in the UI instead of blanking the window.
  const spec = ICONS[name];
  if (!spec) {
    return (
      <svg
        className={className}
        style={style}
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="currentColor"
        aria-hidden="true"
        focusable="false"
      >
        <circle cx="12" cy="12" r="3" />
      </svg>
    );
  }
  return (
    <svg
      className={className}
      style={style}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
    >
      <path d={spec.d} />
      {spec.d2 && <path d={spec.d2} />}
    </svg>
  );
}

/** Icon paired with a label, used by rail items and buttons. */
export function iconForCategory(id: string): IconName {
  switch (id) {
    case 'all':
      return 'apps';
    case 'active':
      return 'download';
    case 'finished':
      return 'check_circle';
    case 'programs':
      return 'settings';
    case 'music':
      return 'library_music';
    case 'video':
      return 'videocam';
    case 'games':
      return 'sports_esports';
    case 'documents':
      return 'description';
    case 'archives':
      return 'folder_zip';
    default:
      return 'category';
  }
}
